CREATE TABLE IF NOT EXISTS conversations (
 user_id BIGINT NOT NULL, chat_id VARCHAR(100) NOT NULL, title VARCHAR(200) NOT NULL,
 payload MEDIUMTEXT NOT NULL, revision BIGINT NOT NULL DEFAULT 1,
 updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 PRIMARY KEY(user_id,chat_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS library_files (
 id CHAR(36) NOT NULL PRIMARY KEY, user_id BIGINT NOT NULL, name VARCHAR(255) NOT NULL,
 mime VARCHAR(100) NOT NULL, size_bytes INT NOT NULL, content MEDIUMBLOB NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, deleted_at TIMESTAMP NULL,
 INDEX(user_id,deleted_at), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
